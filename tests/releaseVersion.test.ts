import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';

test('Windows release version synchronization produces config accepted by the installed Tauri CLI', () => {
  const root = process.cwd();
  const fixture = mkdtempSync(path.join(tmpdir(), 'vana-release-version-'));
  const configPath = path.join(fixture, 'src-tauri/tauri.conf.json');
  try {
    mkdirSync(path.join(fixture, 'src-tauri/src'), { recursive: true });
    writeFileSync(path.join(fixture, 'src-tauri/Cargo.toml'), '[package]\nname = "vana"\nversion = "0.7.0"\nedition = "2021"\n');
    writeFileSync(path.join(fixture, 'src-tauri/src/main.rs'), 'fn main() {}\n');
    for (const file of ['package.json', 'package-lock.json', 'src-tauri/tauri.conf.json', 'src-tauri/Cargo.lock']) {
      copyFileSync(path.join(root, file), path.join(fixture, file));
    }
    // Exercise cleanup of configuration generated by the previous script.
    const legacy = JSON.parse(readFileSync(configPath, 'utf8'));
    legacy.bundle.windows.version = '0.7.0.0';
    writeFileSync(configPath, JSON.stringify(legacy));

    const beforeInvalid = readFileSync(path.join(fixture, 'package.json'), 'utf8');
    assert.throws(() => execFileSync(process.execPath, [path.join(root, 'scripts/sync-version.mjs'), 'invalid'], { cwd: fixture, stdio: 'pipe' }));
    assert.equal(readFileSync(path.join(fixture, 'package.json'), 'utf8'), beforeInvalid);
    for (const [version, msi] of [['0.7.1', '0.7.1.0'], ['0.8.0-beta.1', '0.8.0.1'], ['0.8.0', undefined]] as const) {
      execFileSync(process.execPath, [path.join(root, 'scripts/sync-version.mjs'), version!, ...(msi ? [msi] : [])], { cwd: fixture });
      const config = JSON.parse(readFileSync(configPath, 'utf8'));
      assert.equal(config.version, version);
      assert.match(readFileSync(path.join(fixture, 'src-tauri/Cargo.lock'), 'utf8'),
        new RegExp('name = "vana"\\nversion = "' + version.replaceAll('.', '\\.') + '"'));
      assert.equal(config.bundle.windows.wix.version, msi);
      execFileSync(process.execPath, [path.join(root, 'node_modules/@tauri-apps/cli/tauri.js'), 'inspect', 'wix-upgrade-code'], {
        cwd: fixture, stdio: 'pipe', env: { ...process.env, TAURI_PLATFORM: 'windows' },
      });
    }
  } finally {
    rmSync(fixture, { recursive: true, force: true });
  }
});
